/**
 * Probe: WHY do 17 mutation sites newly survive silently after the field near-miss detector?
 *
 * The harness's `newHoles` bucket carries a hard instruction — "do NOT re-bless, investigate
 * the parser change that stopped catching these mutants" (`mutationHarness.shard*.test.ts:50`).
 * The ledger is the authoritative PRE-arc measurement: a site absent from `RAW_HOLES` at
 * `origin/main` did not alarm before, by construction. So the open question is not WHETHER these
 * are new; it is the MECHANISM. This probe answers it per site, on the live tree.
 *
 * For each named site it prints the verdict, the baseline vs mutant warning-code multisets, and
 * the codes that the mutation REMOVED versus ADDED. The claim under test is narrow and falsifiable:
 * every one of these sites lost `UNKNOWN_FIELD` and nothing else, i.e. the only signal the old
 * parser raised on that mutation came from the positional venue sweep this arc deleted. Any site
 * that lost some OTHER code, or that lost nothing at all, refutes the claim and is a genuine parser
 * regression to fix rather than a ledger row to write.
 *
 * usage: pnpm exec tsx docs/superpowers/specs/parser/probes/2026-08-16-newhole-mechanism-probe.ts
 */
