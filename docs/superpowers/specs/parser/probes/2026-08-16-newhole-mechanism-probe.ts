/** `runShard.withSlug`'s key shape, inverted: "<op>:<slug>:<rest>" with op containing ':'. */
function splitSiteId(siteId: string): { op: string; slug: string; rest: string } {
  for (const op of ["blank-row:remove", "blank-row:inject", "header-typo", "section-reorder"]) {
    if (siteId.startsWith(op + ":")) {
      const tail = siteId.slice(op.length + 1);
      const cut = tail.indexOf(":B");
      return { op, slug: tail.slice(0, cut), rest: tail.slice(cut + 1) };
    }
  }
  throw new Error(`unrecognized operator prefix in ${siteId}`);
}

const codesOf = (p: ReturnType<typeof capture>): string[] =>
  (p.warnings ?? []).map((w) => w.code).sort();

const multisetDiff = (from: string[], to: string[]): string[] => {
  const remaining = [...to];
  const gone: string[] = [];
  for (const c of from) {
    const i = remaining.indexOf(c);
    if (i === -1) gone.push(c);
    else remaining.splice(i, 1);
  }
  return gone;
};

let refuted = 0;
for (const key of NEW_HOLES) {
  const { op, slug, rest } = splitSiteId(key);
  const fixture = FIXTURES.find((f) => f.slug === slug);
  if (!fixture) {
    console.log(`${key}\n  NO FIXTURE for slug ${slug}`);
    refuted++;
    continue;
  }
  const md = readFixture(fixture);
  const wantSiteId = `${op}:${rest}`;
  let found = false;
  for (const m of boundedMutants(op, md)) {
    if (m.siteId !== wantSiteId) continue;
    found = true;
    const b = capture(md, `${slug}.md`);
    const mu = capture(m.md, `${slug}.md`);
    const bc = codesOf(b);
    const mc = codesOf(mu);
    const removed = multisetDiff(bc, mc);
    const added = multisetDiff(mc, bc);
    const onlyUnknownField = removed.length > 0 && removed.every((c) => c === "UNKNOWN_FIELD");
    if (!onlyUnknownField || added.length > 0) refuted++;
    console.log(
      [
        key,
        `  verdict:  ${verdict(b, mu)}`,
        `  removed:  ${removed.length ? removed.join(", ") : "(none)"}`,
        `  added:    ${added.length ? added.join(", ") : "(none)"}`,
        `  claim:    ${onlyUnknownField && added.length === 0 ? "HOLDS" : "REFUTED"}`,
      ].join("\n"),
    );
    break;
  }
  if (!found) {
    console.log(`${key}\n  SITE NOT GENERATED by ${op} on ${slug}`);
    refuted++;
  }
}

console.log(`\nSUMMARY ${NEW_HOLES.length - refuted}/${NEW_HOLES.length} hold, ${refuted} refuted`);
