/**
 * `pnpm gen:sw`: bundles the service worker (lib/offline/worker/entry.ts) with
 * esbuild into lib/offline/__generated__/swSource.ts, a committed module that
 * exports the bundle as one string. The /sw.js route serves that string
 * (spec 4.1, 4.9).
 *
 * tests/lib/offline/swSourceFreshness.test.ts fails when the committed string
 * is not what `buildSwSource()` returns now, so a change to any module the
 * worker imports must be followed by `pnpm gen:sw` (the gen:spec-codes pattern).
 */
import { build } from "esbuild";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const ENTRY_POINT = "lib/offline/worker/entry.ts";
const OUTPUT_PATH = "lib/offline/__generated__/swSource.ts";

/**
 * The worker bundle, and every source file that went into it (repo-relative
 * paths). The working directory is pinned to the repo root, so the path
 * comments esbuild writes into the bundle are the same on every machine.
 */
export async function buildSwSource(): Promise<{ code: string; inputs: string[] }> {
  const result = await build({
    absWorkingDir: REPO_ROOT,
    entryPoints: [ENTRY_POINT],
    bundle: true,
    format: "iife",
    platform: "browser",
    target: ["es2020"],
    write: false,
    metafile: true,
    minify: false,
    legalComments: "none",
  });
  const [output, ...rest] = result.outputFiles;
  if (output === undefined || rest.length > 0) {
    throw new Error(`Expected one bundle from ${ENTRY_POINT}, got ${result.outputFiles.length}.`);
  }
  return { code: output.text, inputs: Object.keys(result.metafile.inputs).sort() };
}

function renderSwSourceModule(code: string): string {
  return (
    "// Generated by scripts/generate-sw-source.ts (pnpm gen:sw). Do not edit by hand.\n" +
    `export const SW_SOURCE: string = ${JSON.stringify(code)};\n`
  );
}

async function main(): Promise<void> {
  const { code, inputs } = await buildSwSource();
  const outputPath = join(REPO_ROOT, OUTPUT_PATH);
  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, renderSwSourceModule(code));
  console.log(`Generated ${OUTPUT_PATH}: ${code.length} characters from ${inputs.length} files.`);
}

const invokedPath = process.argv[1] ? fileURLToPath(import.meta.url) === process.argv[1] : false;
if (invokedPath) {
  main().catch((error: unknown) => {
    console.error(error);
    process.exitCode = 1;
  });
}
